"""Make tools/dev/serve/i18n_apply.lua: one command-bar line in Studio puts the translation
modules into the place and patches the changed client scripts in place (a find/replace of
each changed block, so newer Studio-only edits elsewhere in those scripts are kept).

Usage:  python tools/i18n/studio_sync.py [base-ref]      (default base: HEAD = the last commit)
Then serve tools/dev/serve with tools/dev/serve.ps1 and paste the printed line into the
Studio command bar (Edit mode). It prints one line per file: ok / missing block / created.
"""
import os, sys, subprocess, difflib, shutil, glob

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASE = sys.argv[1] if len(sys.argv) > 1 else 'HEAD'
OUT = os.path.join(ROOT, 'tools', 'dev', 'serve')
BS = chr(92)

def lua_long(s):
    eq = '='
    while (']' + eq + ']') in s: eq += '='
    return '[' + eq + '[\n' + s + ']' + eq + ']'

def inst_path(rel):
    # src/StarterPlayer/StarterPlayerScripts/FashionGame/X.client.lua -> game path parts
    p = rel.replace(BS, '/').split('/')[1:]
    name = p[-1]
    for suf in ('.client.lua', '.server.lua', '.lua'):
        if name.endswith(suf): name = name[:-len(suf)]; break
    return p[:-1] + [name]

def main():
    os.makedirs(OUT, exist_ok=True)
    changed = subprocess.run(['git', 'diff', '--name-only', BASE, '--', 'src'], cwd=ROOT, capture_output=True, text=True).stdout.split()
    untracked = subprocess.run(['git', 'ls-files', '--others', '--exclude-standard', 'src'], cwd=ROOT, capture_output=True, text=True).stdout.split()
    files, patches = [], []
    for rel in sorted(set(changed + untracked)):
        if not rel.endswith('.lua'): continue
        new = open(os.path.join(ROOT, rel), encoding='utf-8').read().replace('\r\n', '\n')
        old = subprocess.run(['git', 'show', '%s:%s' % (BASE, rel)], cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
        parts = inst_path(rel)
        cls = 'LocalScript' if rel.endswith('.client.lua') else 'Script' if rel.endswith('.server.lua') else 'ModuleScript'
        if old.returncode != 0 or '/I18n/' in rel or rel.endswith('/L.lua'):
            # new file (or generated table): send it whole
            fname = '_'.join(parts[-2:]) + '.lua'
            open(os.path.join(OUT, fname), 'w', encoding='utf-8', newline='\n').write(new)
            files.append((parts, cls, fname))
            continue
        a = old.stdout.replace('\r\n', '\n').split('\n')
        b = new.split('\n')
        sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
        for tag, i1, i2, j1, j2 in sm.get_opcodes():
            if tag == 'equal': continue
            lo, hi = max(0, i1 - 1), min(len(a), i2 + 1)
            oldb = '\n'.join(a[lo:hi])
            newb = '\n'.join(a[lo:i1] + b[j1:j2] + a[i2:hi])
            patches.append((parts, oldb, newb))
    with open(os.path.join(OUT, 'i18n_apply.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- generated by tools/i18n/studio_sync.py\n')
        f.write('local HS, SES = game:GetService("HttpService"), game:GetService("ScriptEditorService")\n')
        f.write('local function find(parts, cls, make)\n'
                '\tlocal node = game:GetService(parts[1])\n'
                '\tfor i = 2, #parts do\n'
                '\t\tlocal c = node:FindFirstChild(parts[i])\n'
                '\t\tif not c and make then\n'
                '\t\t\tc = Instance.new(if i == #parts then cls else "Folder")\n'
                '\t\t\tc.Name = parts[i]; c.Parent = node\n'
                '\t\tend\n'
                '\t\tif not c then return nil end\n'
                '\t\tnode = c\n'
                '\tend\n'
                '\treturn node\n'
                'end\n')
        f.write('local function set(s, src) SES:UpdateSourceAsync(s, function() return src end) end\n')
        f.write('local log = {}\n')
        for parts, cls, fname in files:
            f.write('do local s = find({%s}, "%s", true)\n' % (', '.join('"%s"' % p for p in parts), cls))
            f.write('\tlocal src = HS:GetAsync("http://localhost:8765/%s")\n' % fname)
            f.write('\tset(s, src); table.insert(log, "file %s " .. #src) end\n' % '.'.join(parts))
        for parts, oldb, newb in patches:
            f.write('do local s = find({%s})\n' % ', '.join('"%s"' % p for p in parts))
            f.write('\tlocal old, new = %s, %s\n' % (lua_long(oldb), lua_long(newb)))
            f.write('\tif not s then table.insert(log, "MISSING script %s") else\n' % '.'.join(parts))
            f.write('\tlocal src = string.gsub(s.Source, "\\r\\n", "\\n")\n')
            f.write('\tlocal a, b = string.find(src, old, 1, true)\n')
            f.write('\tif string.find(src, new, 1, true) then table.insert(log, "already %s")\n' % parts[-1])
            f.write('\telseif not a then table.insert(log, "BLOCK NOT FOUND %s")\n' % parts[-1])
            f.write('\telse set(s, string.sub(src, 1, a - 1) .. new .. string.sub(src, b + 1)); table.insert(log, "patched %s") end end end\n' % parts[-1])
        f.write('print(table.concat(log, "\\n"))\n')
    print('files', len(files), 'patches', len(patches))
    print('Command bar line:')
    print('local H=game:GetService("HttpService") local w=H.HttpEnabled H.HttpEnabled=true local ok,e=pcall(function() loadstring(H:GetAsync("http://localhost:8765/i18n_apply.lua"))() end) H.HttpEnabled=w print(ok,e)')

if __name__ == '__main__':
    main()
