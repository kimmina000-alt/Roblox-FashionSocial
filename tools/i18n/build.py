"""Build the translation modules src/ReplicatedStorage/FashionGame/Shared/I18n/<lang>.lua.

Input:
  tools/i18n/strings.tsv   from extract.py: id \t kind \t Korean \t uses \t where
  tools/i18n/tr/*.tsv      translations, wide: first line "id\ten\tes\t..." (any language order),
                           then one line per id. \n inside a cell = a new line.
                           A later file wins over an earlier one (fixes: tr/zz_fix.tsv).
Checks: unknown ids, missing translations, {n} placeholders that do not match the Korean.
Usage: python tools/i18n/build.py
"""
import os, re, glob, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LANGS = ['en', 'es', 'pt', 'fr', 'de', 'it', 'ja', 'zh-cn', 'zh-tw', 'ru', 'th', 'tr', 'vi', 'id', 'pl', 'ar']
OUT = os.path.join(ROOT, 'src', 'ReplicatedStorage', 'FashionGame', 'Shared', 'I18n')
BS = chr(92)  # backslash

def unesc(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == BS and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': '\n', 't': '\t', BS: BS}.get(n, BS + n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)

def lua_str(s):
    out = ['"']
    for ch in s:
        if ch == BS: out.append(BS + BS)
        elif ch == '"': out.append(BS + '"')
        elif ch == '\n': out.append(BS + 'n')
        elif ch == '\t': out.append(BS + 't')
        elif ch == '\r': pass
        else: out.append(ch)
    out.append('"')
    return ''.join(out)

def main():
    src = {}
    for ln in open(os.path.join(ROOT, 'tools', 'i18n', 'strings.tsv'), encoding='utf-8'):
        f = ln.rstrip('\n').split('\t')
        src[f[0]] = unesc(f[2])
    tr = collections.defaultdict(dict)
    unknown = 0
    for path in sorted(glob.glob(os.path.join(ROOT, 'tools', 'i18n', 'tr', '*.tsv'))):
        lines = open(path, encoding='utf-8').read().split('\n')
        head = lines[0].rstrip('\r').split('\t')
        assert head[0] == 'id', path
        for no, ln in enumerate(lines[1:], 2):
            ln = ln.rstrip('\r')
            if not ln.strip() or ln.startswith('#'): continue
            f = ln.split('\t')
            if len(f) != len(head):
                print('%s:%d: %d cells, want %d' % (os.path.basename(path), no, len(f), len(head))); continue
            if f[0] not in src:
                unknown += 1; continue
            for lang, cell in zip(head[1:], f[1:]):
                if cell.strip(): tr[lang][f[0]] = unesc(cell)
    os.makedirs(OUT, exist_ok=True)
    bad = 0
    for lang in LANGS:
        rows = []
        for sid, ko in src.items():
            t = tr[lang].get(sid)
            if t is None: continue
            if t.strip() == '∅': t = ''  # ∅ = shown as nothing (Korean particles)
            want = sorted(set(re.findall(r'\{\d+\}', ko)))
            got = sorted(set(re.findall(r'\{\d+\}', t)))
            if want != got:
                bad += 1; print('%s %s placeholders %s vs %s' % (lang, sid, want, got)); continue
            # keep the Korean text's leading / trailing spaces and new lines (it is glued to other text)
            lead = ko[:len(ko) - len(ko.lstrip())]
            trail = ko[len(ko.rstrip()):]
            if t and lead and t[:1] not in (' ', '\n'): t = lead + t
            if t and trail and t[-1:] not in (' ', '\n'): t = t + trail
            rows.append((ko, t))
        with open(os.path.join(OUT, lang + '.lua'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('-- Generated by tools/i18n/build.py from tools/i18n/tr/*.tsv. Do not edit by hand.\n')
            f.write('-- Korean source text -> %s\n' % lang)
            f.write('return {\n')
            for ko, t in sorted(rows):
                f.write('\t[%s] = %s,\n' % (lua_str(ko), lua_str(t)))
            f.write('}\n')
        print('%-6s %4d / %d' % (lang, len(rows), len(src)))
    print('unknown ids (strings no longer in the code):', unknown, '· bad placeholders:', bad)

if __name__ == '__main__':
    main()
